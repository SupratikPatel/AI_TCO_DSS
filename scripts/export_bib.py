"""Export the Source_Registry as BibTeX for the thesis.

Usage: ``uv run python scripts/export_bib.py [--sources PATH] [--out PATH]``

Writes one ``@misc`` entry per source of ``data/sources.json`` to
``thesis/references.bib``, keyed by ``source_id`` and sorted by key, so the
thesis can cite catalog sources as ``\\cite{SOURCE-ID}`` (or ``[@SOURCE-ID]`` in
Pandoc Markdown). The output is deterministic (LF line endings). Do not edit the
generated file by hand; rerun this script after changing ``data/sources.json``.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCES = ROOT / "data" / "sources.json"
DEFAULT_OUT = ROOT / "thesis" / "references.bib"
REQUIRED = ("source_id", "title", "publisher")
SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "_": r"\_",
    "#": r"\#",
    "$": r"\$",
    "{": r"\{",
    "}": r"\}",
}
HEADER = (
    "% Generated by scripts/export_bib.py from data/sources.json. Do not edit by hand.\n"
    "% keywords = Source_Tier (official, third_party, community, formula, assumption).\n"
)


class SourceError(ValueError):
    """A source entry lacks a required field."""


def escape(text: str) -> str:
    return "".join(SPECIALS.get(char, char) for char in text)


def _entry(source: dict[str, Any]) -> str:
    fields = [
        ("title", "{" + escape(source["title"]) + "}"),
        ("author", "{{" + escape(source["publisher"]) + "}}"),
    ]
    if source.get("url"):
        fields.append(("howpublished", "{\\url{" + source["url"] + "}}"))
    if source.get("reference"):
        fields.append(("note", "{" + escape(source["reference"]) + "}"))
    fields.append(("keywords", "{" + escape(str(source.get("tier", ""))) + "}"))
    body = ",\n".join(f"  {name} = {value}" for name, value in fields)
    return f"@misc{{{source['source_id']},\n{body}\n}}\n"


def to_bibtex(sources: list[dict[str, Any]]) -> str:
    """BibTeX text for `sources`; raises `SourceError` naming the source and field."""
    for index, source in enumerate(sources):
        for field in REQUIRED:
            value = source.get(field)
            if not isinstance(value, str) or not value.strip():
                name = source.get("source_id") or f"entry {index}"
                raise SourceError(f"{name}: missing or empty field {field}")
    ordered = sorted(sources, key=lambda s: str(s["source_id"]))
    return HEADER + "".join("\n" + _entry(s) for s in ordered)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sources", type=Path, default=DEFAULT_SOURCES)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        sources = json.loads(args.sources.read_text(encoding="utf-8"))["sources"]
        text = to_bibtex(sources)
    except (OSError, KeyError, json.JSONDecodeError, SourceError) as exc:
        print(f"export_bib: {args.sources}: {exc}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(text.encode("utf-8"))
    print(f"export_bib: wrote {len(sources)} entries to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
